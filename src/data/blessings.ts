export const BLESSINGS_BY_ID: Record<string, BlessingDefinition> = Object.fromEntries(
  BLESSINGS.map((b) => [b.id, b]),
);

export function getBlessing(id: string): BlessingDefinition {
  const b = BLESSINGS_BY_ID[id];
  if (!b) throw new Error(`Unknown blessing: ${id}`);
  return b;
}

export function blessingsByRarity(rarity: BlessingRarity): BlessingDefinition[] {
  return BLESSINGS.filter((b) => b.rarity === rarity && b.offerable !== false);
}
